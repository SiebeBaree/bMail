import { z } from "zod";

import { addressSchema, recipientSchema } from "./common";
import { conversationSchema } from "./conversations";
import { deliveryStatuses, directions } from "./vocabulary";

export const attachmentSchema = z
    .object({
        id: z.uuid(),
        filename: z.string(),
        contentType: z.string(),
        size: z.number().int(),
        contentId: z.string().nullable(),
    })
    .meta({ id: "Attachment" });

/** The original destination of a tracked link, so the app can open it directly instead of through the redirect. */
export const trackedLinkSchema = z
    .object({
        id: z.uuid(),
        url: z.string(),
    })
    .meta({ id: "TrackedLink" });

export const messageSchema = z
    .object({
        id: z.uuid(),
        conversationId: z.uuid(),
        mailboxId: z.uuid(),
        direction: z.enum(directions),
        deliveryStatus: z.enum(deliveryStatuses).nullable(),
        messageIdHeader: z.string().nullable(),
        from: addressSchema,
        to: z.array(addressSchema),
        cc: z.array(addressSchema),
        bcc: z.array(addressSchema),
        replyTo: z.array(addressSchema),
        subject: z.string(),
        html: z.string().nullable(),
        text: z.string().nullable(),
        snippet: z.string(),
        sentAt: z.iso.datetime(),
        trackingEnabled: z.boolean(),
        attachments: z.array(attachmentSchema),
        links: z.array(trackedLinkSchema),
    })
    .meta({ id: "Message" });

export const sendMessageSchema = z
    .object({
        /** Generated by the app and used as Resend's idempotency key, so a retried send never goes out twice. */
        id: z.uuid(),
        /** An existing conversation makes this a reply; a new id starts a conversation. */
        conversationId: z.uuid(),
        mailboxId: z.uuid(),
        to: z.array(recipientSchema).min(1, "Add at least one recipient.").max(50),
        cc: z.array(recipientSchema).max(50).default([]),
        bcc: z.array(recipientSchema).max(50).default([]),
        subject: z.string().trim().max(998),
        html: z.string().max(2_000_000),
        text: z.string().max(1_000_000),
        trackingEnabled: z.boolean().default(false),
        /** Uploads created with POST /uploads. */
        attachmentIds: z.array(z.uuid()).max(20).default([]),
    })
    .meta({ id: "SendMessage" });

/** Resend accepts 40 MB per email; this leaves room for the encoding overhead. */
export const MAX_UPLOAD_BYTES = 25 * 1024 * 1024;

export const createUploadSchema = z
    .object({
        filename: z.string().trim().min(1).max(255),
        contentType: z.string().min(1).max(255),
        size: z.number().int().min(1).max(MAX_UPLOAD_BYTES, "Attachments can be up to 25 MB."),
    })
    .meta({ id: "CreateUpload" });

/** Where the app PUTs the file, with the same content type it declared. */
export const uploadSchema = z
    .object({
        id: z.uuid(),
        uploadUrl: z.url(),
        expiresAt: z.iso.datetime(),
    })
    .meta({ id: "Upload" });

export const sentMessageSchema = z
    .object({
        conversation: conversationSchema,
        message: messageSchema,
    })
    .meta({ id: "SentMessage" });

export const attachmentUrlSchema = z
    .object({
        url: z.url(),
        expiresAt: z.iso.datetime(),
    })
    .meta({ id: "AttachmentUrl" });

export type Attachment = z.infer<typeof attachmentSchema>;
export type Message = z.infer<typeof messageSchema>;
export type SendMessageInput = z.infer<typeof sendMessageSchema>;
export type CreateUploadInput = z.infer<typeof createUploadSchema>;
export type Upload = z.infer<typeof uploadSchema>;
export type SentMessage = z.infer<typeof sentMessageSchema>;
