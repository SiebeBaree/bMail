import { z } from "zod";

/** The app's own labels, shared by every account. */
export const labelSchema = z
    .object({
        id: z.uuid(),
        name: z.string(),
        /** What belongs under the label, in your words. Auto labelling only applies labels that have one. */
        description: z.string().nullable(),
        createdAt: z.iso.datetime(),
        deletedAt: z.iso.datetime().nullable(),
    })
    .meta({ id: "Label" });

const labelName = z.string().trim().min(1, "Give the label a name.").max(50, "Label names can be up to 50 characters.");
/** Empty clears it. */
const labelDescription = z.string().trim().max(500, "Descriptions can be up to 500 characters.").nullable();

export const createLabelSchema = z
    .object({
        /** Generated by the app, so a retried create returns the label it already made. */
        id: z.uuid(),
        name: labelName,
    })
    .meta({ id: "CreateLabel" });

/** Changes what's given. Older apps only send a name. */
export const updateLabelSchema = z
    .object({
        name: labelName.optional(),
        description: labelDescription.optional(),
    })
    .meta({ id: "UpdateLabel" });

/** Every label on one conversation. Any conversation id works, including Gmail ones. */
export const conversationLabelsSchema = z
    .object({
        conversationId: z.uuid(),
        labelIds: z.array(z.uuid()),
    })
    .meta({ id: "ConversationLabels" });

/** Replaces the whole set. An empty list removes every label. */
export const setConversationLabelsSchema = z
    .object({
        labelIds: z.array(z.uuid()).max(50),
    })
    .meta({ id: "SetConversationLabels" });

export type Label = z.infer<typeof labelSchema>;
export type CreateLabelInput = z.infer<typeof createLabelSchema>;
export type UpdateLabelInput = z.infer<typeof updateLabelSchema>;
export type ConversationLabels = z.infer<typeof conversationLabelsSchema>;
